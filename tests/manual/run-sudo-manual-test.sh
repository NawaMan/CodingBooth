# Manual Test: --sudo flag, config.toml sudo = false, and the no-sudo template
#
# Runs the whole sudo checklist by itself. Each step prints the command, what
# the booth actually answered, and a verdict — so you can confirm it with your
# own eyes, without typing anything. Exits non-zero if any step fails.
#
#   Part 1  the runtime flag              (plain project, base image)
#   Part 2  config.toml sudo = false      (booth config --set sudo=false)
#   Part 3  the no-sudo template          (booth config --select no-sudo/apt-pkg:figlet)
#   Part 4  a keep-alive --no-sudo booth  (exec into it, try sudo apt-get)
#
# Projects are generated by booth config in /tmp and removed afterwards, along
# with the image Part 3 builds and the booth Part 4 keeps alive.
#
# Usage: tests/manual/run-sudo-manual-test.sh [--skip-build]

set -uo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/../.." && pwd)"
BOOTH_BIN="$ROOT_DIR/codingbooth"
export CB_TEMPLATES_PATH="$ROOT_DIR/templates"

[[ "${1:-}" == "--skip-build" ]] || "$ROOT_DIR/build/cli-build.sh" >/dev/null

WORK="$(mktemp -d "${TMPDIR:-/tmp}/cb-sudo-manual.XXXXXX")"
LOG="$WORK/booth.log"          # booth's stderr, if a step needs explaining
# Folder names become booth and image names, so they carry the PID: never one
# of yours.
PLAIN="$WORK/cb-sudo-plain-$$"             # no .booth: base image, defaults
CONFIGURED="$WORK/cb-sudo-configured-$$"   # config.toml sudo = false, no Boothfile
TEMPLATE="$WORK/cb-sudo-template-$$"       # no-sudo template + an apt package
KEEP_NAME="cb-sudo-manual-$$"
mkdir -p "$PLAIN" "$CONFIGURED" "$TEMPLATE"

cleanup() {
  docker rm -f "$KEEP_NAME" >/dev/null 2>&1 || true
  local img
  for img in $(docker images --format '{{.Repository}}:{{.Tag}}' codingbooth-local \
                 | grep "^codingbooth-local:$(basename "$TEMPLATE")-" || true); do
    docker rmi "$img" >/dev/null 2>&1 || true
  done
  rm -rf "$WORK"
}
trap cleanup EXIT

PASSED=0
FAILED=0
OUT=""

part() { printf '\n\033[1m━━ %s ━━\033[0m\n' "$1"; }

# run <dir> <booth args...> — prints the command, runs it there, shows the
# answer. The booth's stdout lands in $OUT; its stderr goes to $LOG.
run() {
  local dir="$1"; shift
  printf '   \033[2m$ (in %s) booth %s\033[0m\n' "${dir#"$WORK"/}" "$*"
  OUT="$(cd "$dir" && "$BOOTH_BIN" "$@" 2>>"$LOG")"
  printf '%s\n' "${OUT:-<no output>}" | tail -4 | sed 's/^/   → /'
}

# check <n> <what> <ok?> <expected> — the verdict for one step
check() {
  if [[ "$3" == "true" ]]; then
    printf '   ✅ %s. %s\n' "$1" "$2"; PASSED=$((PASSED + 1))
  else
    printf '   ❌ %s. %s — expected %s\n' "$1" "$2" "$4"; FAILED=$((FAILED + 1))
  fi
}

ok() { "$@" && echo true || echo false; }      # ok <command> → true/false
has() { [[ "$OUT" == *"$1"* ]]; }              # has <text>: is it in the answer?

# What every sudo probe runs: the answer, then the exit code on its own line.
SUDO_WHOAMI='sudo -n whoami 2>&1; echo "exit=$?"'
refused() { [[ "$OUT" == *"exit=1"* && "$OUT" != *root* ]]; }
granted() { [[ "$OUT" == *$'root\nexit=0'* ]]; }

echo "═══════════════════════════════════════════════════════════"
echo "  --sudo flag, config.toml, no-sudo template — Manual Test"
echo "  work folder: $WORK"
echo "═══════════════════════════════════════════════════════════"

# ─── Part 1: the runtime flag ───────────────────────────────────────────────
part "Part 1: runtime flag (--sudo)"

echo " 1. no flag — sudo is on by default"
run "$PLAIN" --variant base -- "$SUDO_WHOAMI"
check 1 "no flag gives root" "$(ok granted)" "root, exit=0"

echo " 2. --sudo true"
run "$PLAIN" --variant base --sudo true -- "$SUDO_WHOAMI"
check 2 "--sudo true gives root" "$(ok granted)" "root, exit=0"

echo " 3. --sudo false"
run "$PLAIN" --variant base --sudo false -- "$SUDO_WHOAMI"
check 3 "--sudo false refuses sudo" "$(ok refused)" "a sudo error, exit=1"

echo " 4. --no-sudo"
run "$PLAIN" --variant base --no-sudo -- "$SUDO_WHOAMI"
check 4 "--no-sudo refuses sudo" "$(ok refused)" "a sudo error, exit=1"

echo " 5. --sudo false keeps what the image installed"
run "$PLAIN" --variant base --sudo false -- 'command -v git curl'
check 5 "git and curl are still there" \
  "$(has bin/git && has bin/curl && echo true || echo false)" "paths to git and curl"

# ─── Part 2: config.toml ────────────────────────────────────────────────────
part "Part 2: config.toml sudo = false"

echo "    setup: booth config --no-tui --set sudo=false"
(cd "$CONFIGURED" && "$BOOTH_BIN" config --no-tui --set sudo=false >/dev/null 2>>"$LOG")
grep -n '^sudo' "$CONFIGURED/.booth/config.toml" 2>/dev/null | sed 's/^/   → config.toml:/'

echo " 6. config.toml sudo = false, no flag"
run "$CONFIGURED" -- "$SUDO_WHOAMI"
check 6 "config.toml alone refuses sudo" "$(ok refused)" "a sudo error, exit=1"

echo " 7. config.toml sudo = false, --sudo true"
run "$CONFIGURED" --sudo true -- "$SUDO_WHOAMI"
check 7 "--sudo true overrides config.toml" "$(ok granted)" "root, exit=0"

# ─── Part 3: the no-sudo template ───────────────────────────────────────────
part "Part 3: no-sudo template"

echo " 8. booth config --select no-sudo/apt-pkg:figlet"
(cd "$TEMPLATE" && "$BOOTH_BIN" config --no-tui --select 'no-sudo/apt-pkg:figlet' >/dev/null 2>>"$LOG")
CONFIG_LINE="$(grep '^sudo' "$TEMPLATE/.booth/config.toml" 2>/dev/null)"
printf '   → config.toml: %s\n' "${CONFIG_LINE:-<no sudo line>}"
check 8 "the template writes sudo = false" "$([[ "$CONFIG_LINE" == "sudo = false" ]] && echo true || echo false)" "sudo = false"

echo " 9. run it — sudo refused, but apt installed figlet at build time"
echo "    (first run builds the project image; this takes a minute)"
run "$TEMPLATE" --silence-build -- "command -v figlet; $SUDO_WHOAMI"
check 9 "sudo is refused" "$(ok refused)" "a sudo error, exit=1"
check 9 "figlet is installed — sudo goes after the build" \
  "$(ok has /usr/bin/figlet)" "/usr/bin/figlet"

echo "10. same project, --sudo true"
run "$TEMPLATE" --silence-build --sudo true -- "$SUDO_WHOAMI"
check 10 "--sudo true overrides the template" "$(ok granted)" "root, exit=0"

# ─── Part 4: an interactive-style session ───────────────────────────────────
part "Part 4: keep-alive booth with --no-sudo"

echo "11. booth --no-sudo --keep-alive --daemon, then exec 'sudo apt-get update' into it"
run "$PLAIN" --variant base --no-sudo --keep-alive --daemon --name "$KEEP_NAME"
run "$PLAIN" exec --name "$KEEP_NAME" -- bash -c 'sudo -n apt-get update 2>&1 | tail -1; echo "exit=${PIPESTATUS[0]}"'
check 11 "sudo apt-get update is refused in the session" "$(ok refused)" "a sudo error, exit=1"

# ─── Summary ────────────────────────────────────────────────────────────────
echo
echo "═══════════════════════════════════════════════════════════"
if [[ $FAILED -eq 0 ]]; then
  echo "  ✅ All $PASSED checks passed"
else
  echo "  ❌ $FAILED failed, $PASSED passed — booth's stderr: $LOG (kept)"
  trap - EXIT
  docker rm -f "$KEEP_NAME" >/dev/null 2>&1 || true
fi
echo "═══════════════════════════════════════════════════════════"
exit $(( FAILED > 0 ))
