# Regenerates the list of built-in setup/install script names that gets embedded
# into the codingbooth binary.
#
# The Boothfile compiler validates `setup <tool>` / `install <mgr>` names against
# this list. It cannot scan variants/base/setups/ at runtime because end users only
# ever have the binary, not the CodingBooth source tree — see FindBuiltinSetupsDir().
#
# Usage:
#   build/gen-builtin-scripts.sh           # regenerate
#   build/gen-builtin-scripts.sh --check   # fail if out of date (for CI)

set -Eeuo pipefail
trap 'echo "❌ Error on line $LINENO"; exit 1' ERR

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SETUPS_DIR="${ROOT}/variants/base/setups"
OUT_FILE="${ROOT}/cli/src/pkg/boothfile/builtin-scripts.txt"

[ -d "$SETUPS_DIR" ] || { echo "❌ Not found: ${SETUPS_DIR}"; exit 1; }

generate() {
    cat <<'EOF'
# Generated by build/gen-builtin-scripts.sh -- DO NOT EDIT BY HAND.
# Built-in script names available in the base image, used by the Boothfile
# compiler to validate `setup <tool>` and `install <manager>` names.
# Format: "setup <name>" or "install <name>", one per line.
EOF
    # shellcheck disable=SC2012
    ls "$SETUPS_DIR" \
        | sed -n 's/--setup\.sh$//p'   | LC_ALL=C sort -u | sed 's/^/setup /'
    # shellcheck disable=SC2012
    ls "$SETUPS_DIR" \
        | sed -n 's/--install\.sh$//p' | LC_ALL=C sort -u | sed 's/^/install /'
}

if [ "${1:-}" = "--check" ]; then
    if diff -q <(generate) "$OUT_FILE" >/dev/null 2>&1; then
        echo "✅ ${OUT_FILE#"$ROOT"/} is up to date."
        exit 0
    fi
    echo "❌ ${OUT_FILE#"$ROOT"/} is out of date. Run: build/gen-builtin-scripts.sh" >&2
    diff <(generate) "$OUT_FILE" | head -20 >&2 || true
    exit 1
fi

generate > "$OUT_FILE"
SETUP_COUNT=$(grep -c '^setup '   "$OUT_FILE" || true)
INSTALL_COUNT=$(grep -c '^install ' "$OUT_FILE" || true)
echo "✅ Wrote ${OUT_FILE#"$ROOT"/} (${SETUP_COUNT} setup, ${INSTALL_COUNT} install scripts)."
