func TestSerializeConfigToml_ValidToml(t *testing.T) {
	cfg := &ConfigToml{
		Variant: "codeserver",
		Port:    "8080",
		RunArgs: []string{"-e", "KEY=value with spaces"},
	}
	result := SerializeConfigToml(cfg, "", "")

	// Verify scalar key=value lines have properly quoted string values.
	// Skip comment lines, blank lines, array brackets, and array element lines.
	lines := strings.Split(result, "\n")
	for _, line := range lines {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") ||
			strings.HasPrefix(line, "]") || strings.HasPrefix(line, `"`) {
			continue
		}
		// Only check top-level scalar assignments (key = value)
		if strings.Contains(line, " = ") {
			parts := strings.SplitN(line, " = ", 2)
			if len(parts) == 2 {
				key := strings.TrimSpace(parts[0])
				val := strings.TrimSpace(parts[1])
				// Skip array headers like "run-args = ["
				if strings.HasPrefix(val, "[") {
					continue
				}
				// Boolean values don't need quoting
				if val == "true" || val == "false" {
					continue
				}
				assert.True(t, strings.HasPrefix(val, `"`),
					"scalar value for %q should be quoted: %s", key, line)
			}
		}
	}
}
