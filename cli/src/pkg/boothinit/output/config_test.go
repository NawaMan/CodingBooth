func TestSerializeConfigToml_FullConfig(t *testing.T) {
	cfg := &ConfigToml{
		Variant:   "codeserver",
		Port:      "NEXT",
		Timezone:  "Asia/Bangkok",
		Dind:      true,
		Cmds:      []string{"bash"},
		BuildArgs: []string{"--build-arg", "NODE_VERSION=20"},
		RunArgs:   []string{"-e", "TZ=Asia/Bangkok"},
	}
	result := SerializeConfigToml(cfg, "", "")

	// Verify ordering: scalar fields first, then arrays
	variantIdx := strings.Index(result, "variant")
	cmdsIdx := strings.Index(result, "cmds")
	buildArgsIdx := strings.Index(result, "build-args")
	runArgsIdx := strings.Index(result, "run-args")

	assert.True(t, variantIdx < cmdsIdx, "variant should come before cmds")
	assert.True(t, cmdsIdx < buildArgsIdx, "cmds should come before build-args")
	assert.True(t, buildArgsIdx < runArgsIdx, "build-args should come before run-args")
}

